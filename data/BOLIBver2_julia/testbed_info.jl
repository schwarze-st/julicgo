# Helper function to access problem info (similar to MATLAB function)
function get_problem_info(prob_name::Union{String, Int})
    # If integer, map to problem name (optional numbering)
    if prob_name isa Int
        # You could add a mapping from number to name here
        error("Integer problem lookup not implemented. Use problem name string.")
    end
    
    if haskey(BILEVEL_PROBLEMS, prob_name)
        return BILEVEL_PROBLEMS[prob_name]
    else
        error("Problem '$prob_name' not found in BILEVEL_PROBLEMS dictionary.")
    end
end

